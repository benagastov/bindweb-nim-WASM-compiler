/**
 * site-template.js — everything the Build button needs to turn the linked
 * .wasm modules into a small static website in the deployed-site folder:
 *
 *   index.html                    generated shell (this file, below) with the
 *                                 whole JS runtime inlined as minified
 *                                 classic <script> blocks
 *   <name>.wasm                   one self-contained module per project
 *                                 .nim file (from compileToWasm); the
 *                                 entry's wasm is the one index.html boots
 *
 * A generated site is just those two kinds of files — there is no
 * nim-runtime/ folder. The runtime modules are ES modules in web/src/ but
 * are inlined into index.html as classic scripts: stripEsmExports()
 * removes the `export` prefixes and minifyInlineRuntime() lightly
 * minifies the result, so the deployed page runs the EXACT same code the
 * IDE's Run button used — no bundler, no divergence. (Only a hand-edited
 * index.html still gets nim-runtime/* written next to it, so legacy pages
 * referencing nim-runtime/*.js keep working; see the Build handler.)
 *
 * The inlined runtime is additionally OBFUSCATED: the four minified
 * scripts (wasi-shim, bindweb-runtime, run-wasm, boot) are concatenated
 * into ONE payload, XOR+base64 encoded, and emitted as a single tiny
 * decoder <script> that runs `(new Function(decode("...")))()` — so
 * view-source and the site file tree show only gibberish. The small
 * config script setting window.__APP_WASM_URL__ (+ the gate globals)
 * stays plaintext: the in-IDE preview's rewriteSiteUrls /
 * disarmDomainGateForPreview depend on its exact shape, and boot reads
 * the globals via window.* which works from inside the Function scope.
 *
 * The pure functions (stripEsmExports, minifyInlineRuntime,
 * rewriteSiteUrls, mimeFor, encodeRuntimePayload, decodeRuntimePayload,
 * generateSiteIndex) are exported for tests/site-template.test.mjs and
 * are safe to import in Node.
 */

/** Marker comment identifying a generated (i.e. safely regenerable) index.html. */
export const SITE_GENERATED_MARKER = 'generated by Nim Playground Build';

/**
 * Runtime modules inlined into the generated index.html on every Build
 * (in this order). `src` is resolved against the page (dist root); `dest`
 * is the path inside the deployed-site folder — now used only as the
 * script's display name and, for hand-edited (legacy) index.html files,
 * as the on-disk nim-runtime/ path that keeps old <script src> references
 * working.
 */
export const RUNTIME_SITE_FILES = [
  { src: './src/runtime/wasi-shim.js', dest: 'nim-runtime/wasi-shim.js' },
  { src: './src/runtime/bindweb-browser-runtime.js', dest: 'nim-runtime/bindweb-runtime.js' },
  { src: './src/runtime/run-wasm.js', dest: 'nim-runtime/run-wasm.js' },
];

/**
 * Turn an ES module into a classic script: drop `export default …;`
 * statements and `export ` prefixes (all our runtime modules use only
 * those two forms at the start of a line).
 *
 * @param {string} src ES module source
 * @returns {string} classic-script source
 */
export function stripEsmExports(src) {
  return src
    .replace(/^export\s+default\s+[^;]*;?[ \t]*$/gm, '')
    .replace(/^export\s+/gm, '');
}

/**
 * Conservative minifier for the runtime code inlined into the generated
 * index.html, so the deployed page doesn't ship readable "engine" source.
 * Deliberately line-oriented and string-safe — it never scans inside a
 * line of code, so string/regex contents are always preserved verbatim:
 *
 *   - strips block comments whose `/*` is the first non-whitespace token
 *     of a line (all runtime block comments are such JSDoc banners);
 *     an inline `/*` inside code or a string is left untouched;
 *   - strips full-line `//` comments (first non-whitespace chars `//`);
 *     inline `//` comments after code are kept;
 *   - trims trailing whitespace;
 *   - collapses runs of 2+ blank lines into one.
 *
 * Nothing is renamed and no code is reordered, so the minified source is
 * still the exact same program, just without the commentary.
 *
 * @param {string} code classic-script source (post stripEsmExports)
 * @returns {string} minified source
 */
export function minifyInlineRuntime(code) {
  const out = [];
  let inBlock = false;
  let lastWasBlank = true; // also suppresses leading blank lines
  for (const rawLine of String(code).split('\n')) {
    let line = rawLine.replace(/[ \t\r]+$/, '');
    let start = line.trimStart();
    if (inBlock) {
      const close = start.indexOf('*/');
      if (close === -1) continue; // whole line inside a block comment
      inBlock = false;
      start = start.slice(close + 2).trimStart(); // keep any code after */
      if (start === '') continue;
      line = start;
    }
    if (start.startsWith('/*')) {
      const close = start.indexOf('*/', 2);
      if (close === -1) { inBlock = true; continue; }
      const rest = start.slice(close + 2).trimStart(); // one-line /* ... */
      if (rest === '') continue;
      line = rest;
    } else if (start.startsWith('//')) {
      continue; // full-line comment
    }
    if (line === '') {
      if (lastWasBlank) continue;
      lastWasBlank = true;
    } else {
      lastWasBlank = false;
    }
    out.push(line);
  }
  return out.join('\n');
}

/**
 * Point a site file's relative references at blob: URLs. Every quoted
 * occurrence of a known site path ("main.wasm", 'nim-runtime/boot.js',
 * also with a "./" prefix) is replaced by that file's blob URL, so an
 * index.html read from the virtual site folder can run from a blob/srcdoc
 * document where relative fetches would not resolve.
 *
 * @param {string} html source text (typically index.html)
 * @param {Map<string, string>} urlMap site path -> blob: URL
 * @returns {string} rewritten source
 */
export function rewriteSiteUrls(html, urlMap) {
  let out = html;
  for (const [path, url] of urlMap) {
    for (const p of [path, `./${path}`]) {
      out = out.split(`"${p}"`).join(`"${url}"`);
      out = out.split(`'${p}'`).join(`'${url}'`);
    }
  }
  return out;
}

/**
 * Disarm the domain-binding boot gate for the in-IDE site preview: replace
 * the embedded `window.__BINDWEB_BOUND_DOMAINS__ = [...];` assignment with
 * an empty list, so the boot script never arms __BINDWEB_DOMAIN_ENFORCE__.
 * The preview runs in an srcdoc iframe on the IDE host (e.g. localhost),
 * which is development mode — the README promises that is never blocked.
 * Real static hosting keeps enforcement: this transform is applied ONLY to
 * the srcdoc document, never to the index.html written into the Site
 * folder by Build. The pattern matches the exact shape generateSiteIndex
 * emits (JSON.stringify never escapes "]").
 *
 * @param {string} html rewritten preview document (post rewriteSiteUrls)
 * @returns {string} document with the bound-domains list emptied
 */
export function disarmDomainGateForPreview(html) {
  return String(html).replace(
    /window\.__BINDWEB_BOUND_DOMAINS__ = \[[^\]]*\];/,
    'window.__BINDWEB_BOUND_DOMAINS__ = [];'
  );
}

/**
 * Best-effort MIME type by file extension (for blob URLs).
 *
 * @param {string} path
 * @returns {string}
 */
export function mimeFor(path) {
  const ext = path.slice(path.lastIndexOf('.') + 1).toLowerCase();
  switch (ext) {
    case 'html': case 'htm': return 'text/html';
    case 'js': case 'mjs': return 'text/javascript';
    case 'css': return 'text/css';
    case 'wasm': return 'application/wasm';
    case 'json': case 'map': return 'application/json';
    case 'png': return 'image/png';
    case 'jpg': case 'jpeg': return 'image/jpeg';
    case 'gif': return 'image/gif';
    case 'webp': return 'image/webp';
    case 'svg': return 'image/svg+xml';
    case 'ico': return 'image/x-icon';
    case 'txt': case 'md': case 'nim': case 'nimble': return 'text/plain';
    case 'ttf': return 'font/ttf';
    case 'woff': return 'font/woff';
    case 'woff2': return 'font/woff2';
    default: return 'application/octet-stream';
  }
}

/**
 * Normalize a hostname for domain-binding comparisons: trim, lowercase,
 * strip an optional scheme, drop any path/query/fragment and port, and
 * strip one leading "www.". Applied to BOTH sides of every comparison so
 * `bindDomain("https://www.Example.com:8080/x")` matches a visit to
 * `example.com`. Byte-for-byte the same logic as the guard in
 * runtime/bindweb-browser-runtime.js and the normalizer inlined into
 * SITE_BOOT_JS (the scheme is only stripped when it is a real, anchored
 * `scheme://` prefix), so boot gate and runtime guard never disagree.
 *
 * @param {string} d raw domain/URL/hostname
 * @returns {string} normalized hostname ("" for empty input)
 */
export function normalizeDomainName(d) {
  return String(d == null ? '' : d).trim().toLowerCase()
    .replace(/^[a-z][a-z0-9+.-]*:\/\//, '')
    .split(/[/?#]/)[0]
    .split(':')[0]
    .replace(/^www\./, '');
}

/**
 * Scan Nim sources for `bindDomain("...")` / `bind_domain("...")` calls
 * and return the unique, normalized, sorted list of bound domains.
 *
 * @param {Iterable<string>} sources decoded .nim sources
 * @returns {string[]} bound domains (possibly empty)
 */
export function collectBoundDomains(sources) {
  const re = /bind_?[dD]omain\s*\(\s*"([^"]+)"/g;
  const found = new Set();
  for (const src of sources || []) {
    if (typeof src !== 'string') continue;
    for (const m of src.matchAll(re)) {
      const d = normalizeDomainName(m[1]);
      if (d) found.add(d);
    }
  }
  return [...found].sort();
}

/** Escape a string for use inside HTML text/attribute context. */
function escapeHtml(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/**
 * Escape a string for use inside a double-quoted JavaScript string in an
 * inline <script> (HTML entities are NOT decoded there, so escapeHtml is
 * the wrong tool; "</" is escaped to keep the script tag intact).
 */
function escapeJsString(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/<\//g, '<\\/');
}

/* --------------------------------------------------------------------------
 * Runtime payload obfuscation (Feature: obfuscate the inlined JS runtime).
 *
 * The whole inlined runtime — wasi-shim + bindweb-runtime + run-wasm + boot,
 * concatenated in execution order — is encoded as UTF-8 bytes XORed with a
 * fixed key and base64'd, then emitted as one tiny generic-looking decoder
 * script: `(new Function(decode("...")))()`. This is obfuscation, NOT
 * encryption: the key ships next to the payload (the decoder needs it), so
 * a determined reader can decode it in seconds. The point is that
 * view-source, the site file tree and a casual DevTools peek show gibberish
 * instead of readable engine source.
 *
 * Why ONE payload: the four runtime scripts reference each other's
 * top-level declarations (createWasiShim / ProcExit / createBindwebRunner /
 * runWasmApp / the boot IIFE). Declarations inside a `new Function` body do
 * NOT leak to window, so they must all live in the same body — and nothing
 * outside the payload may reference them (verified: the page's only other
 * scripts are the plaintext config globals, which the payload reads via
 * window.*).
 *
 * Accepted residual: the wasm import keys (bindweb_js_flush, bindweb_wgpu_*,
 * ...) remain visible inside the decoded payload — they are dictated by the
 * wasm binary's import section and cannot be renamed.
 * ------------------------------------------------------------------------ */

/** Fixed XOR key for the payload encoding (ships with the decoder). */
const PAYLOAD_XOR_KEY = 'bindweb';

/** Bytes <-> base64 without stack-overflowing on large payloads. */
function bytesToBase64(bytes) {
  let bin = '';
  const CHUNK = 0x8000;
  for (let i = 0; i < bytes.length; i += CHUNK) {
    bin += String.fromCharCode.apply(null, bytes.subarray(i, i + CHUNK));
  }
  return btoa(bin);
}

function base64ToBytes(b64) {
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

/**
 * Encode a JavaScript source string as the obfuscated runtime payload:
 * UTF-8 bytes XORed with the fixed key, base64'd.
 *
 * @param {string} source concatenated runtime source
 * @returns {string} base64 payload
 */
export function encodeRuntimePayload(source) {
  const bytes = new TextEncoder().encode(String(source));
  const key = new TextEncoder().encode(PAYLOAD_XOR_KEY);
  const xored = new Uint8Array(bytes.length);
  for (let i = 0; i < bytes.length; i++) xored[i] = bytes[i] ^ key[i % key.length];
  return bytesToBase64(xored);
}

/**
 * Inverse of encodeRuntimePayload — exported for the tests, which decode
 * the emitted payload and assert on (and execute) the real source.
 *
 * @param {string} b64 base64 payload
 * @returns {string} the original JavaScript source
 */
export function decodeRuntimePayload(b64) {
  const xored = base64ToBytes(b64);
  const key = new TextEncoder().encode(PAYLOAD_XOR_KEY);
  const bytes = new Uint8Array(xored.length);
  for (let i = 0; i < xored.length; i++) bytes[i] = xored[i] ^ key[i % key.length];
  return new TextDecoder().decode(bytes);
}

/**
 * The tiny generic-looking decoder <script> emitted into the generated
 * index.html in place of the readable runtime sources. `decode` is a plain
 * top-level function (classic-script scope), the payload runs inside one
 * `new Function` body so all four runtime scripts share a single scope.
 * The base64 alphabet never contains "</", so this block is inline-script
 * safe regardless of the payload contents.
 */
function runtimePayloadScript(b64) {
  return '<script>function decode(s){'
    + `var k="${PAYLOAD_XOR_KEY}",b=atob(s),a=new Uint8Array(b.length),i=0;`
    + 'for(;i<b.length;i++)a[i]=b.charCodeAt(i)^k.charCodeAt(i%k.length);'
    + 'return new TextDecoder().decode(a)}\n'
    + `(new Function(decode("${b64}")))();</script>`;
}

/**
 * The generated index.html for the deployed site: a minimal page with an
 * #app mount point (bindweb DOM/canvas apps render here) and a
 * #nim-console output area (echo/stdout lands here). The whole JS runtime
 * is inlined as ONE obfuscated payload script (the minified scripts
 * concatenated in their original execution order, XOR+base64 encoded,
 * decoded and run via `(new Function(decode("...")))()` — one shared
 * function scope replaces the old shared global scope), so a generated
 * site is index.html + *.wasm only and view-source shows no readable
 * engine code.
 *
 * Inline-<script> safety: a literal "</script" inside a script body would
 * close the tag early and break the page. The standard fix — escaping to
 * "<\/script" — is only valid inside string literals; applied blindly it
 * would corrupt a regex literal or a `</` division/comparison. Grepping
 * web/src/runtime/*.js and SITE_BOOT_JS shows NO "</script" (indeed no
 * "</" at all) in any context, so the sources are inlined verbatim and
 * any future runtime file that introduces "</script" fails the Build with
 * a clear error naming the file, rather than shipping a corrupted page.
 *
 * @param {string} title page title (usually the project entry file name)
 * @param {string} [wasmPath] site-relative path of the entry wasm the boot
 *   script fetches (e.g. "main.wasm"); mirrors the entry .nim path with
 *   the extension swapped. Defaults to the legacy "app.wasm".
 * @param {Array<{name: string, code: string}>} [runtimeScripts] runtime
 *   sources to inline, in execution order (wasi-shim, bindweb-runtime,
 *   run-wasm, boot). Each `code` is inlined verbatim after a "</script"
 *   check, then minified.
 * @param {object} [opts]
 * @param {string[]} [opts.boundDomains] normalized hostnames the app is
 *   bound to via bindDomain("..."); embedded as
 *   window.__BINDWEB_BOUND_DOMAINS__ so the boot script can arm the
 *   enforce flag and abort before any fetch on a foreign domain.
 * @param {string[]} [opts.wasmManifest] every wasm written this build,
 *   entry FIRST, then the rest sorted; embedded as
 *   window.__APP_WASM_MANIFEST__ so the boot script fetches them strictly
 *   one-by-one (a clean network tab on foreign domains, a predictable
 *   load order otherwise).
 * @returns {string} full HTML document
 */
export function generateSiteIndex(title, wasmPath = 'app.wasm', runtimeScripts = [], opts = {}) {
  // Concatenate the minified runtime scripts + boot into ONE payload (they
  // share a single new Function scope — see the obfuscation notes above),
  // then XOR+base64 encode it so the emitted document shows only gibberish.
  // The "</script" check still runs on the raw sources: a stray one would
  // be harmless after base64, but it almost always indicates a bug in the
  // runtime source, so keep failing the Build loudly.
  const parts = [];
  for (const { name, code } of runtimeScripts) {
    if (/<\/script/i.test(code)) {
      throw new Error(
        `cannot inline ${name} into index.html: it contains "</script", which ` +
        'would break out of the inline <script> block. Move that string into ' +
        'the .wasm side or split it (e.g. "<" + "/script").'
      );
    }
    parts.push(`/* ${name} — inlined (minified) by Nim Playground Build */\n${minifyInlineRuntime(code)}`);
  }
  const payloadScript = parts.length
    ? runtimePayloadScript(encodeRuntimePayload(parts.join('\n')))
    : '';
  // Domain-binding / load-order globals for the boot script's pre-fetch
  // gate. JSON.stringify keeps the values safely quoted; the in-IDE site
  // preview's rewriteSiteUrls() rewrites the quoted manifest paths to
  // blob: URLs just like the entry wasm path above.
  const wasmManifest = Array.isArray(opts.wasmManifest) ? opts.wasmManifest : [];
  const boundDomains = Array.isArray(opts.boundDomains) ? opts.boundDomains : [];
  const gateGlobals = [];
  if (wasmManifest.length) {
    gateGlobals.push(`window.__APP_WASM_MANIFEST__ = ${JSON.stringify(wasmManifest)};`);
  }
  if (boundDomains.length) {
    gateGlobals.push(`window.__BINDWEB_BOUND_DOMAINS__ = ${JSON.stringify(boundDomains)};`);
  }
  const gateScript = gateGlobals.length ? `<script>${gateGlobals.join('')}</script>\n` : '';
  return `<!DOCTYPE html>
<!-- ${SITE_GENERATED_MARKER} — safe to regenerate; delete this comment and Build will keep your edits -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${escapeHtml(title)}</title>
<style>
  body { margin: 0; font-family: system-ui, -apple-system, "Segoe UI", sans-serif; background: #f2f3f4; color: #1a1d22; }
  #app { min-height: 50vh; }
  #nim-console {
    margin: 24px; padding: 12px 16px;
    background: #101216; color: #d6d9de;
    font: 12px/1.55 ui-monospace, "Cascadia Code", Menlo, Consolas, monospace;
    border-radius: 8px; white-space: pre-wrap; word-break: break-word;
  }
  #nim-console:empty { display: none; }
  #nim-console .stderr { color: #c07a7a; }
</style>
</head>
<body>
<div id="app"></div>
<pre id="nim-console"></pre>
<!-- The quoted "${wasmPath}" below is deliberate: the in-IDE site preview
     rewrites quoted file references in THIS document to blob: URLs, so the
     boot script picks up the rewritten URL via the global. On real static
     hosting the plain relative path is served as-is. -->
<script>window.__APP_WASM_URL__ = "${escapeJsString(wasmPath)}";</script>
${gateScript}${payloadScript}
</body>
</html>
`;
}

/**
 * The static boot script inlined into the generated index.html on every
 * Build (and still written to nim-runtime/boot.js for hand-edited legacy
 * pages). Fetches the entry wasm named by window.__APP_WASM_URL__ (a
 * relative URL on real static hosting; rewritten to a blob: URL by the
 * in-IDE site preview) and runs it through the exact same runWasmApp the
 * IDE's Run button uses.
 */
export const SITE_BOOT_JS = `/* nim-runtime/boot.js — written by Nim Playground Build.
 * Loads the entry wasm (window.__APP_WASM_URL__) and runs it with the same
 * runtime as the IDE's Run button. When the app called bindDomain("..."),
 * Build also embedded the bound hostnames and the full wasm manifest into
 * index.html: the boot then refuses to start on a foreign domain — before
 * ANY fetch — and otherwise fetches the manifest strictly one-by-one. */
(async () => {
  const out = document.getElementById('app');
  const consoleEl = document.getElementById('nim-console');
  const onLog = (msg, kind) => {
    if (!consoleEl) return;
    const span = document.createElement('span');
    if (kind === 'stderr' || kind === 'error') span.className = 'stderr';
    span.textContent = msg + '\\n';
    consoleEl.appendChild(span);
  };
  // Same normalization as the runtime guard: trim, lowercase, strip an
  // anchored scheme, drop path/query/fragment and port, strip one leading
  // "www." — byte-for-byte runtime/bindweb-browser-runtime.js's logic.
  const normDomain = (h) => {
    let s = String(h == null ? '' : h).trim().toLowerCase();
    s = s.replace(/^[a-z][a-z0-9+.-]*:\\/\\//, '');
    s = s.split(/[/?#]/)[0].split(':')[0];
    if (s.startsWith('www.')) s = s.slice(4);
    return s;
  };
  // -- PRE-FETCH domain gate --------------------------------------------
  // window.__BINDWEB_BOUND_DOMAINS__ is embedded by Build when the app
  // called bindDomain("..."). On a foreign domain the boot wipes the page,
  // shows a fake server 404 and ABORTS before any fetch — the network tab
  // stays clean, there is nothing to steal.
  const boundDomains = Array.isArray(window.__BINDWEB_BOUND_DOMAINS__) ? window.__BINDWEB_BOUND_DOMAINS__ : [];
  if (boundDomains.length) {
    window.__BINDWEB_DOMAIN_ENFORCE__ = true; // arms the runtime guard too
    const host = normDomain(typeof location !== 'undefined' ? location.hostname : '');
    if (!boundDomains.some((d) => normDomain(d) === host)) {
      // Fake Flask-style server 404: a bare document, default-serif on
      // white, no app chrome, no console reveal — a thief sees a boring
      // server error, not a protection mechanism. Identical wording to
      // lockOutForDomain() in runtime/bindweb-browser-runtime.js.
      if (document.body) {
        document.body.innerHTML = '';
        document.body.style.cssText = 'background:#fff;color:#000;font-family:serif;';
      }
      const h1 = document.createElement('h1');
      h1.textContent = 'Not Found';
      const p = document.createElement('p');
      p.textContent = 'The requested URL was not found on the server. If you entered the URL manually please check your spelling and try again.';
      const target = document.body || document.documentElement;
      target.appendChild(h1);
      target.appendChild(p);
      return;
    }
  }
  try {
    // Set by an inline script in index.html: a plain relative wasm path on
    // real hosting, a blob: URL inside the IDE's site preview iframe.
    const url = window.__APP_WASM_URL__ || 'app.wasm';
    // The wasm manifest (every wasm written this build, entry FIRST, then
    // the rest sorted) is fetched STRICTLY one-by-one: sequential awaits in
    // manifest order, any non-200 aborts with a deliberately vague error.
    // Non-entry bytes are fetched for the gate only — the app re-fetches
    // them itself if it uses them. Legacy hand-edited pages have no
    // manifest global and keep the old single-fetch path.
    const hasManifest = Array.isArray(window.__APP_WASM_MANIFEST__) && window.__APP_WASM_MANIFEST__.length;
    const manifest = hasManifest ? window.__APP_WASM_MANIFEST__ : [url];
    let entryBytes = null;
    for (const path of manifest) {
      const res = await fetch(path); // sequential on purpose — one-by-one
      if (!res.ok) throw new Error(hasManifest ? 'failed to load the application' : url + ': HTTP ' + res.status);
      const bytes = await res.arrayBuffer();
      if (entryBytes === null) entryBytes = bytes; // manifest[0] is the entry
    }
    await runWasmApp({
      wasmBytes: entryBytes,
      outputEl: out,
      onLog,
      createBindwebRunner,
      createWasiShim,
      ProcExit,
    });
  } catch (e) {
    onLog('failed to start: ' + ((e && e.message) || e), 'error');
  }
})();
`;
