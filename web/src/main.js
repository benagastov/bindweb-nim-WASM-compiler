/**
 * main.js — UI glue for the nim-wasm-compiler IDE (SPEC §8c:
 * non-programmer-friendly, one big Run button, examples, honest
 * download progress, friendly errors).
 *
 * Wires the editor, console log pane and app output pane to the compile
 * pipeline (web/src/pipeline.js). No frameworks, no bundler: plain ES
 * modules loaded via <script type="module">.
 *
 * Served from the dist root (tools/make-dist.sh copies web/ to dist/), so
 * vendor/ and libpacks/ are sibling directories — see `config` below.
 *
 * Download progress: the big vendor wasm files are fetched ONCE here with
 * a ReadableStream reader so the byte count (and MB label) is real. The
 * fetched nim.wasm / nim-bundle.data bytes are handed to the Nim compiler
 * as blob: URLs through its `preloaded` option, so those are never
 * downloaded twice. The clang worker re-fetches its own files by URL
 * inside a Web Worker (no way to hand it blobs from here); on a served
 * dist the browser HTTP cache normally makes that second read free.
 */

