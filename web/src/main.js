/* --------------------------------------------------------------------------
 * First-visit download with honest byte counting (SPEC §8c).
 * ------------------------------------------------------------------------ */

/** Format a byte count as a short MB string. */
function mb(bytes) {
  return (bytes / (1024 * 1024)).toFixed(0);
}

/**
 * Fetch one vendor file, counting bytes as they stream in.
 *
 * @param {{path: string, size: number, label: string}} file entry from VENDOR_FILES
 * @param {(done: number) => void} onBytes called with the cumulative count
 * @returns {Promise<Blob|null>} the file contents, or null if missing
 */
async function prefetchFile(file, onBytes) {
  const url = `${config.vendorUrl}/${file.path}`;
  let response;
  try {
    response = await fetch(url);
  } catch (e) {
    return null; // network hiccup: let the real loader surface the error
  }
  if (!response.ok || !response.body) return null; // optional file absent

  const reader = response.body.getReader();
  const chunks = [];
  let received = 0;
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    chunks.push(value);
    received += value.length;
    onBytes(value.length);
  }
  const type = file.path.endsWith('.wasm') ? 'application/wasm' : '';
  return new Blob(chunks, { type });
}

/**
 * Download every vendor file once, narrating progress in MB. Returns the
 * nim files as blobs so NimCompiler can load them from blob: URLs instead
 * of fetching them a second time.
 *
 * @returns {Promise<Map<string, Blob>>} basename -> blob for nim files
 */
async function prefetchVendor() {
  const total = VENDOR_FILES.reduce((acc, f) => acc + f.size, 0);
  let done = 0;
  progressWrap.classList.add('visible');
  const update = (label) => {
    const pct = Math.min(100, (done / total) * 100);
    progressBar.style.width = `${pct}%`;
    progressLabel.textContent =
      `Downloading the compiler (first visit only)… ${mb(done)} of about ${mb(total)} MB — ${label}`;
  };

  const preloaded = new Map();
  update('starting');
  for (const file of VENDOR_FILES) {
    update(file.label);
    const blob = await prefetchFile(file, (n) => {
      done += n;
      update(file.label);
    });
    if (blob && file.path.startsWith('nim/')) {
      preloaded.set(file.path.slice('nim/'.length), blob);
    }
  }
  progressBar.style.width = '100%';
  progressWrap.classList.remove('visible');
  return preloaded;
}

