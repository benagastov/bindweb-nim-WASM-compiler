let nim = null;
let clang = null;

/**
 * Map a pipeline result to a one-line plain-English summary plus the raw
 * compiler output for the collapsible details (SPEC §8c).
 *
 * @param {{stage: string, error?: string, nimStdout: string,
 *   nimStderr: string, clangLog: string}} result
 * @returns {{summary: string, raw: string}}
 */
function friendlyError(result) {
  const raw = [
    result.error || '',
    result.nimStderr || '',
    result.nimStdout || '',
    result.clangLog || '',
  ].filter((s) => s && s.trim()).join('\n\n');

  if (result.stage === 'nim') {
    // Typical Nim error: "/project/main.nim(4, 10) Error: undeclared identifier: 'foo'"
    const m = /main\.nim\((\d+),\s*\d+\)\s*Error:\s*(.+)/.exec(result.nimStderr || '');
    if (m) {
      return { summary: `The Nim compiler didn't understand line ${m[1]}: ${m[2]}`, raw };
    }
    return { summary: "The Nim compiler couldn't understand your code. Details below.", raw };
  }
  if (result.stage === 'clang') {
    return { summary: 'The C build step reported a problem. Details below.', raw };
  }
  return { summary: `Your app was built, but it failed to start: ${result.error || 'unknown error'}`, raw };
}

/**
 * Load both toolchains in parallel after the one-time download; enable
 * the run button when ready.
 */
async function init() {
  setStatus('Loading compiler (first visit downloads about 75 MB)…', 'busy');
  try {
    const preloaded = await prefetchVendor();
    setStatus('Starting the compiler…', 'busy');
    nim = new NimCompiler({
      vendorUrl: config.vendorUrl,
      libpacksUrl: config.libpacksUrl,
      onLog: log,
      preloaded,
    });
    clang = new ClangCompiler({ vendorUrl: config.vendorUrl, onLog: log });
    await Promise.all([nim.init(), clang.init()]);
    setStatus('Ready — press Run', 'ok');
    log('ready — press Run to build and run your program', 'ok');
    runBtn.disabled = false;
  } catch (e) {
    setStatus('The compiler failed to load', 'err');
    log(`initialization failed: ${e.message || e}`, 'error');
    showError(
      'The compiler could not be loaded. Check your internet connection and reload the page.',
      `initialization failed: ${e.message || e}\n\nexpected layout: ./vendor/nim/*, ./vendor/clang/*, ./libpacks/manifest.json next to index.html`
    );
  }
}

runBtn.addEventListener('click', async () => {
  runBtn.disabled = true;
  consoleEl.innerHTML = '';
  outputEl.innerHTML = '';
  hideError();
  const t0 = performance.now();
  try {
    const result = await compileAndRun({
      source: editor.value,
      nim,
      clang,
      runtime: { createBindwebRunner },
      outputEl,
      onLog: (msg, kind) => {
        log(msg, kind);
        // Plain-English status narration for each pipeline stage (SPEC §8c).
        if (kind === 'step') {
          if (msg.includes('step 1')) setStatus('Translating Nim to C…', 'busy');
          else if (msg.includes('step 2')) setStatus('Preparing the C code…', 'busy');
          else if (msg.includes('step 3')) setStatus('Compiling C to WebAssembly…', 'busy');
          else if (msg.includes('step 4')) setStatus('Running your app…', 'busy');
        }
      },
    });
    const dt = ((performance.now() - t0) / 1000).toFixed(1);
    if (result.ok) {
      setStatus(`Running — done in ${dt}s`, 'ok');
    } else {
      const { summary, raw } = friendlyError(result);
      setStatus('Something went wrong — see the message below', 'err');
      showError(summary, raw);
      log(summary, 'error');
    }
  } catch (e) {
    setStatus('Something went wrong — see the message below', 'err');
    showError('The build stopped unexpectedly. Details below.', e.stack || String(e));
    log(`pipeline error: ${e.message || e}`, 'error');
  } finally {
    runBtn.disabled = false;
  }
});

editor.value = EXAMPLES[0].source;
updateLineNumbers();
init();
