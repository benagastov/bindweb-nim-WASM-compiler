/**
 * Update the status pill.
 *
 * @param {string} text status message
 * @param {'' | 'busy' | 'ok' | 'err'} [kind] visual state
 */
function setStatus(text, kind = '') {
  statusEl.textContent = text;
  statusEl.className = kind;
}

/**
 * Append a line to the console pane.
 *
 * @param {string} msg message text
 * @param {string} [kind] 'step' | 'info' | 'ok' | 'warn' | 'error' |
 *   'stdout' | 'stderr'
 */
function log(msg, kind = 'info') {
  const line = document.createElement('div');
  line.className = `line ${kind}`;
  const stamp = document.createElement('span');
  stamp.className = 't';
  stamp.textContent = new Date().toLocaleTimeString('en-GB', { hour12: false });
  line.appendChild(stamp);
  line.appendChild(document.createTextNode(msg));
  consoleEl.appendChild(line);
  consoleEl.scrollTop = consoleEl.scrollHeight;
}

/** Show the friendly error box (SPEC §8c: never alert()). */
function showError(summary, raw) {
  errorSummary.textContent = summary;
  errorRaw.textContent = raw && raw.trim() ? raw.trim() : '(no further output)';
  errorBox.classList.add('visible');
}

/** Hide the friendly error box (on each new run). */
function hideError() {
  errorBox.classList.remove('visible');
}

/** Refresh the line-number gutter to match the editor content. */
function updateLineNumbers() {
  const count = editor.value.split('\n').length;
  const nums = new Array(count);
  for (let i = 0; i < count; i++) nums[i] = i + 1;
  lineNumbers.textContent = nums.join('\n');
  lineNumbers.scrollTop = editor.scrollTop;
}

editor.addEventListener('input', updateLineNumbers);
editor.addEventListener('scroll', () => {
  lineNumbers.scrollTop = editor.scrollTop;
});
editor.addEventListener('keydown', (e) => {
  if (e.key === 'Tab') {
    e.preventDefault();
    const { selectionStart: start, selectionEnd: end } = editor;
    editor.setRangeText('  ', start, end, 'end');
    updateLineNumbers();
  }
});

